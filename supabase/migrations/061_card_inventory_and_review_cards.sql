CREATE TABLE IF NOT EXISTS public.review_feedback (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  card_profile_id UUID NOT NULL REFERENCES public.card_profiles(id) ON DELETE CASCADE,
  nfc_card_id UUID REFERENCES public.nfc_cards(id) ON DELETE SET NULL,
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  category TEXT CHECK (category IS NULL OR char_length(category) <= 40),
  message TEXT CHECK (message IS NULL OR char_length(message) <= 2000),
  contact_name TEXT CHECK (contact_name IS NULL OR char_length(contact_name) <= 100),
  contact_phone TEXT CHECK (contact_phone IS NULL OR char_length(contact_phone) <= 40),
  contact_email TEXT CHECK (contact_email IS NULL OR char_length(contact_email) <= 200),
  source TEXT NOT NULL DEFAULT 'link' CHECK (source IN ('nfc', 'qr', 'link')),
  visitor_hash TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS review_feedback_profile_idx
  ON public.review_feedback(card_profile_id, created_at DESC);

