-- No INSERT policy on purpose: the only way in is submit_review_feedback(),
-- which checks the card itself rather than trusting ids from the browser.
DROP POLICY IF EXISTS "Owners can read feedback on their cards." ON public.review_feedback;
CREATE POLICY "Owners can read feedback on their cards."
  ON public.review_feedback FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM public.card_profiles cp
      WHERE cp.id = review_feedback.card_profile_id
        AND (cp.user_id = auth.uid() OR cp.org_owner_id = auth.uid())
    )
  );

DROP POLICY IF EXISTS "Admins can read all feedback." ON public.review_feedback;
CREATE POLICY "Admins can read all feedback."
  ON public.review_feedback FOR SELECT
  USING (public.is_admin());

CREATE OR REPLACE FUNCTION public.submit_review_feedback(
  p_username TEXT,
  p_code TEXT,
  p_rating INTEGER,
  p_category TEXT,
  p_message TEXT,
  p_name TEXT,
  p_phone TEXT,
  p_email TEXT,
  p_source TEXT,
  p_visitor_hash TEXT
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_profile UUID;
  v_card UUID;
  v_id UUID;
BEGIN
  SELECT id INTO v_profile
  FROM public.card_profiles
  WHERE username = lower(trim(p_username)) AND published = true;

  IF v_profile IS NULL THEN
    RAISE EXCEPTION 'card not found';
  END IF;

  -- A card code only counts if it is a live card pointing at this profile.
  IF p_code IS NOT NULL AND trim(p_code) <> '' THEN
    SELECT id INTO v_card
    FROM public.nfc_cards
    WHERE card_url = trim(p_code) AND card_profile_id = v_profile AND status = 'active';
  END IF;

  INSERT INTO public.review_feedback
    (card_profile_id, nfc_card_id, rating, category, message,
     contact_name, contact_phone, contact_email, source, visitor_hash)
  VALUES
    (v_profile, v_card, p_rating,
     NULLIF(trim(p_category), ''), NULLIF(trim(p_message), ''),
     NULLIF(trim(p_name), ''), NULLIF(trim(p_phone), ''), NULLIF(trim(p_email), ''),
     CASE WHEN p_source IN ('nfc', 'qr', 'link') THEN p_source ELSE 'link' END,
     p_visitor_hash)
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

REVOKE ALL ON FUNCTION public.submit_review_feedback(TEXT, TEXT, INTEGER, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT) FROM public;
GRANT EXECUTE ON FUNCTION public.submit_review_feedback(TEXT, TEXT, INTEGER, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT) TO anon, authenticated;
